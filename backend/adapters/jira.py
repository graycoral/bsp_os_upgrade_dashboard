"""Jira adapter with conservative recovery after an uncertain create response."""
import os
import re
from urllib.parse import urlparse
import httpx
from backend.adapters.bridge import Bridge


class Jira:
    def __init__(self, profile, transport=None):
        self.profile = profile
        self.transport = transport

    def request(self, method, path, payload=None):
        p = self.profile
        if urlparse(p['jira_url']).scheme != 'https':
            raise ValueError('HTTPS Jira URL required')
        token = os.environ.get(p['jira_auth_env'])
        if not token:
            raise ValueError('credential not configured')
        with httpx.Client(timeout=8, transport=self.transport, follow_redirects=False) as client:
            r = client.request(method, p['jira_url'].rstrip('/')+'/rest/api/'+p['jira_api_version']+path,
                               headers={'Authorization':'Bearer '+token}, json=payload)
            r.raise_for_status()
            return r.json()

    def mcp(self, operation, data):
        p = self.profile
        if not p.get('mcp_argv'):
            raise ValueError('MCP bridge not configured')
        result = Bridge().run(p['mcp_argv'], {'schema_version':1,'operation':operation,'server':p.get('mcp_name'),'scope':p.get('mcp_scope'),'data':data}, p['workspace'], 30)
        if result.get('outcome') != 'SUCCEEDED':
            raise ValueError('MCP operation failed')
        return result

    def search(self, decision_id):
        label='bsp-decision-'+decision_id
        if self.profile['jira_mode']=='claude_mcp':
            return self.mcp('jira_search',{'external_id':label}).get('issues',[])
        # The external marker is generated by this application, not model-provided JQL.
        if not re.fullmatch('[a-f0-9]{32}',decision_id):
            raise ValueError('invalid decision id')
        data=self.request('POST','/search',{'jql':f'labels = "{label}"','fields':['key','status'],'maxResults':2})
        return data.get('issues',[])

    def create(self, decision):
        p=self.profile
        fields={**p.get('jira_fields',{}),'project':{'key':p['jira_project']},'issuetype':{'name':p.get('jira_issue_type','Task')},
                'summary':decision['title'][:240],'labels':['bsp-decision-'+decision['id']]}
        if p['jira_mode']=='claude_mcp':
            return self.mcp('jira_create',{'external_id':'bsp-decision-'+decision['id'],'fields':fields})
        return self.request('POST','/issue',{'fields':fields})

    def ensure_link(self, decision, prior_status):
        try:
            issues=self.search(decision['id'])
            if len(issues)==1 and re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*-\d+',issues[0].get('key','')):
                return {'sync_status':'LINKED','jira_key':issues[0]['key']}
            if len(issues)>1:
                return {'sync_status':'UNKNOWN','sync_detail':'동일 내부 ID의 티켓이 여러 개입니다. 수동 확인 필요.'}
            if prior_status!='QUEUED':
                return {'sync_status':'UNKNOWN','sync_detail':'이전 생성 결과가 불명입니다. 검색에서 찾지 못해도 중복 생성하지 않습니다.'}
            created=self.create(decision)
            if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*-\d+',created.get('key','')):
                raise ValueError('missing key')
            return {'sync_status':'LINKED','jira_key':created['key']}
        except (httpx.HTTPError,ValueError,OSError):
            return {'sync_status':'UNKNOWN','sync_detail':'연결 또는 생성 결과 확인 실패. 내부 판단 항목은 보존됩니다.'}
